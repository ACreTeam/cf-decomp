#include <prfile2/puh_msc.h>

s32 __uhf_msc_cmd_check_sense(u8* sense) {
    switch (UHF_MSC_SENSE_CODE(sense[0], sense[1], sense[2])) {
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NO_SENSE, 0x00, 0x00):
            return UHF_MSC_SENSE_NO_SENSE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_RECOVERED_ERROR, 0x17, 0x01):
            return UHF_MSC_SENSE_RECOVERED_WITH_RETRIES;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_RECOVERED_ERROR, 0x18, 0x00):
            return UHF_MSC_SENSE_RECOVERED_WITH_ECC;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x04, 0x01):
            return UHF_MSC_SENSE_BECOMING_READY;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x04, 0x02):
            return UHF_MSC_SENSE_INIT_REQUIRED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x04, 0x04):
            return UHF_MSC_SENSE_FORMAT_IN_PROGRESS;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x04, 0xFF):
            return UHF_MSC_SENSE_NOT_READY_BUSY;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x06, 0x00):
            return UHF_MSC_SENSE_NO_REFERENCE_POSITION;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x08, 0x00):
            return UHF_MSC_SENSE_COMM_FAILURE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x08, 0x01):
            return UHF_MSC_SENSE_COMM_TIMEOUT;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x08, 0x80):
            return UHF_MSC_SENSE_COMM_OVERRUN;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x3A, 0x00):
            return UHF_MSC_SENSE_MEDIUM_NOT_PRESENT;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x54, 0x00):
            return UHF_MSC_SENSE_INTERFACE_FAILURE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0x80, 0x00):
            return UHF_MSC_SENSE_NOT_READY_VENDOR;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_NOT_READY, 0xFF, 0xFF):
            return UHF_MSC_SENSE_NOT_READY_UNKNOWN;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x02, 0x00):
            return UHF_MSC_SENSE_NO_SEEK_COMPLETE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x03, 0x00):
            return UHF_MSC_SENSE_WRITE_FAULT;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x10, 0x00):
            return UHF_MSC_SENSE_ID_CRC_ERROR;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x11, 0x00):
            return UHF_MSC_SENSE_UNRECOVERED_READ_ERROR;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x12, 0x00):
            return UHF_MSC_SENSE_NO_ID_ADDRESS_MARK;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x13, 0x00):
            return UHF_MSC_SENSE_NO_DATA_ADDRESS_MARK;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x14, 0x00):
            return UHF_MSC_SENSE_RECORD_NOT_FOUND;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x30, 0x01):
            return UHF_MSC_SENSE_UNKNOWN_FORMAT;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_MEDIUM_ERROR, 0x31, 0x01):
            return UHF_MSC_SENSE_FORMAT_FAILED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x1A, 0x00):
            return UHF_MSC_SENSE_PARAM_LIST_LENGTH;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x20, 0x00):
            return UHF_MSC_SENSE_INVALID_OPCODE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x21, 0x00):
            return UHF_MSC_SENSE_LBA_OUT_OF_RANGE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x24, 0x00):
            return UHF_MSC_SENSE_INVALID_FIELD_IN_CDB;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x25, 0x00):
            return UHF_MSC_SENSE_LUN_NOT_SUPPORTED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x26, 0x00):
            return UHF_MSC_SENSE_INVALID_FIELD_IN_PARAM;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x26, 0x01):
            return UHF_MSC_SENSE_PARAM_NOT_SUPPORTED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x26, 0x02):
            return UHF_MSC_SENSE_INVALID_PARAM_VALUE;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ILLEGAL_REQUEST, 0x39, 0x00):
            return UHF_MSC_SENSE_SAVING_NOT_SUPPORTED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_UNIT_ATTENTION, 0x28, 0x00):
            return UHF_MSC_SENSE_MEDIUM_CHANGED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_UNIT_ATTENTION, 0x29, 0x00):
            return UHF_MSC_SENSE_RESET_OCCURRED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_UNIT_ATTENTION, 0x2F, 0x00):
            return UHF_MSC_SENSE_COMMANDS_CLEARED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_DATA_PROTECT, 0x27, 0x00):
            return UHF_MSC_SENSE_WRITE_PROTECTED;
        case UHF_MSC_SENSE_CODE(UHF_MSC_SENSE_KEY_ABORTED_COMMAND, 0x4E, 0x00):
            return UHF_MSC_SENSE_OVERLAPPED_COMMANDS;
        default:
            if ((u16)((sense[0] << 8) | sense[1]) == ((UHF_MSC_SENSE_KEY_HARDWARE_ERROR << 8) | UHF_MSC_ASC_DIAGNOSTIC_FAILURE)) {
                return UHF_MSC_SENSE_DIAGNOSTIC_FAILURE;
            }
            return UHF_MSC_SENSE_UNKNOWN;
    }
}
