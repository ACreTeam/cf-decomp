// 801E3CD8
bool CharSet::add(const CharRange &range) {
    if (containsRange(range)) {
        return false;
    }
    for (u32 i = 0; i < mRanges.size();) {
        if (range.contains(mRanges[i])) {
            mRanges.erase(i);
        } else {
            i++;
        }
    }
    for (u32 i = 0; i < mRanges.size(); i++) {
        if (mRanges[i].contains(range.mLo) || (mRanges[i].mHi != 0xFFFF && range.mLo == mRanges[i].mHi + 1)) {
            if (i != mRanges.size() - 1 &&
                (mRanges[i + 1].contains(range.mHi) ||
                 (range.mHi != 0xFFFF && range.mHi + 1 == mRanges[i + 1].mLo))) {
                mRanges[i].mHi = mRanges[i + 1].mHi;
                mRanges.erase(i + 1);
            } else {
                mRanges[i].mHi = range.mHi;
            }
            return true;
        }
        if (mRanges[i].contains(range.mHi) || (range.mHi != 0xFFFF && range.mHi + 1 == mRanges[i].mLo)) {
            mRanges[i].mLo = range.mLo;
            return true;
        }
    }
    mRanges.insertSorted(range);
    return true;
}

// 801E3EF8
void CharSet::addCaseVariants(u32 flags) {
    int num;
    const CaseMapEntry *map;
    bool unicode;
    if (flags & FLAG_CASE_INSENSITIVE) {
        map = sAsciiCaseMap;
        num = 2;
        unicode = false;
    } else if (flags & FLAG_UNICODE_CASE) {
        map = sUnicodeCaseMap;
        num = 0x310;
        unicode = true;
    } else {
        return;
    }
    for (u32 i = 0; i < mRanges.size(); i++) {
        if (addMappedRanges(mRanges[i], map, num)) {
            i = -1;
        } else if (unicode && addEquivalents(mRanges[i])) {
            i = -1;
        }
    }
}

// 801E3FCC
bool CharSet::addMappedRanges(const CharRange &range, const CaseMapEntry *map, int num) {
    bool changed = false;
    for (int i = 0; i < num; i++) {
        const CaseMapEntry *e = &map[i];
        if (range.mHi < e->mLo) {
            break;
        }
        if (e->mLo <= range.mLo && range.mHi <= e->mHi) {
            if (add(CharRange(range.mLo + e->mDelta, range.mHi + e->mDelta))) {
                changed = true;
            }
        } else if (range.contains(e->mLo)) {
            if (range.contains(e->mHi)) {
                add(CharRange(e->mLo + e->mDelta, e->mHi + e->mDelta));
            } else if (add(CharRange(e->mLo + e->mDelta, range.mHi + e->mDelta))) {
                changed = true;
            }
        } else if (range.contains(e->mHi)) {
            if (add(CharRange(range.mLo + e->mDelta, e->mHi + e->mDelta))) {
                changed = true;
            }
        }
        if (gAllocFailed) {
            return false;
        }
    }
    return changed;
}

// 801E417C
bool CharSet::addEquivalents(const CharRange &range) {
    bool changed = false;
    for (int i = 0; i < 19; i++) {
        int j = 0;
        while (true) {
            if (sCaseEquivSets[i][j] == 0) {
                break;
            }
            if (!range.contains(sCaseEquivSets[i][j])) {
                j++;
                continue;
            }
            int k = 0;
            while (true) {
                u16 ch = sCaseEquivSets[i][k];
                if (ch == 0) {
                    break;
                }
                if (add(CharRange(ch, ch))) {
                    changed = true;
                }
                k++;
            }
            break;
        }
    }
    return changed;
}

