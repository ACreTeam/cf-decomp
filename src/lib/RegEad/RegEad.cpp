// 801E3A9C
bool CharSet::contains(u16 ch) const {
    if (mRanges.size() == 0) {
        return false;
    }
    int lo = 0;
    int hi = mRanges.size() - 1;
    do {
        int mid = lo + ((hi - lo) >> 1);
        if (mRanges[mid].mLo <= ch) {
            if (ch <= mRanges[mid].mHi) {
                return true;
            }
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    } while (hi >= lo);
    return false;
}

