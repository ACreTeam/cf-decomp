// 801E4E0C
const CaseMapEntry *findCaseMapEntry(u32 ch, bool ascii) {
    int lo = 0;
    int hi = ascii ? 2 : 0x310;
    do {
        int mid = lo + ((hi - lo) >> 1);
        const CaseMapEntry *e = (ascii ? sAsciiCaseMap : sUnicodeCaseMap) + mid;
        if (e->mLo <= ch) {
            if (ch <= e->mHi) {
                return e;
            }
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    } while (lo <= hi);
    return NULL;
}

// 801E4E84
const u16 *findCaseEquivSet(u32 ch) {
    for (int i = 0; i < 19; i++) {
        for (int j = 0;; j++) {
            if (ch == sCaseEquivSets[i][j]) {
                return sCaseEquivSets[i];
            }
            if (sCaseEquivSets[i][j] == 0) {
                break;
            }
        }
    }
    return NULL;
}
