// 801E42F0
CharSet &CharSet::intersect(const CharSet &other) {
    u32 i = 0;
    u32 j = 0;
    while (i < mRanges.size() && j < other.mRanges.size()) {
        if (other.mRanges[j].mHi < mRanges[i].mLo) {
            j++;
            continue;
        }
        if (mRanges[i].mHi < other.mRanges[j].mLo) {
            mRanges.erase(i);
            continue;
        }
        CharRange &a = mRanges[i];
        if (other.mRanges[j].contains(a)) {
            i++;
            continue;
        }
        const CharRange &b = other.mRanges[j];
        const CharRange &current = a;
        if (current.contains(b)) {
            u16 oldHi = a.mHi;
            a.mLo = b.mLo;
            a.mHi = b.mHi;
            if (oldHi == other.mRanges[j].mHi) {
                continue;
            }
            mRanges.insertSorted(CharRange(other.mRanges[j].mHi + 1, oldHi));
            if (gAllocFailed) {
                return *this;
            }
            i++;
            j++;
        } else if (current.mLo < b.mLo) {
            a.mLo = other.mRanges[j].mLo;
            i++;
        } else {
            u16 oldHi = a.mHi;
            a.mHi = other.mRanges[j].mHi;
            mRanges.insertSorted(CharRange(other.mRanges[j].mHi + 1, oldHi));
            if (gAllocFailed) {
                return *this;
            }
            i++;
            j++;
        }
    }
    while (i < mRanges.size()) {
        mRanges.erase(i);
    }
    return *this;
}

// 801E44EC
CharSet CharSet::complement() const {
    CharSet result;
    if (mRanges.size() == 0) {
        result.mRanges.push_back(CharRange(0, 0xFFFF));
    } else if (mRanges.size() == 1 && mRanges[0].mLo == 0 && mRanges[0].mHi == 0xFFFF) {
    } else {
        if (mRanges[0].mLo != 0) {
            result.mRanges.push_back(CharRange(0, mRanges[0].mLo - 1));
        }
        for (u32 i = 0; i < mRanges.size() - 1; i++) {
            const CharRange &a = mRanges[i];
            const CharRange &n = mRanges[i + 1];
            result.mRanges.push_back(CharRange(a.mHi + 1, n.mLo - 1));
            if (gAllocFailed) {
                break;
            }
        }
        u16 last = mRanges[mRanges.size() - 1].mHi;
        if (last != 0xFFFF) {
            result.mRanges.push_back(CharRange(last + 1, 0xFFFF));
        }
    }
    return result;
}

// 801E4658
CharSet &CharSet::remove(u16 ch) {
    for (u32 i = 0; i < mRanges.size(); i++) {
        if (ch == mRanges[i].mLo) {
            if (ch == mRanges[i].mHi) {
                mRanges.erase(i);
            } else {
                mRanges[i].mLo = mRanges[i].mLo + 1;
            }
            break;
        }
        if (ch == mRanges[i].mHi) {
            mRanges[i].mHi = mRanges[i].mHi - 1;
            break;
        }
        if (mRanges[i].mLo < ch && ch < mRanges[i].mHi) {
            u16 oldHi = mRanges[i].mHi;
            mRanges[i].mHi = ch - 1;
            mRanges.insertSorted(CharRange(ch + 1, oldHi));
            break;
        }
    }
    return *this;
}

// 801E4750
CharSet &CharSet::remove(const CharRange &range) {
    for (u32 i = 0; i < mRanges.size();) {
        if (range.contains(mRanges[i])) {
            mRanges.erase(i);
        } else {
            i++;
        }
    }
    for (u32 i = 0; i < mRanges.size(); i++) {
        CharRange &cur = mRanges[i];
        u16 lo = range.mLo;
        if (lo == cur.mLo) {
            cur.mLo = range.mHi + 1;
        } else if (cur.contains(lo)) {
            if (range.mHi == cur.mHi) {
                cur.mHi = lo - 1;
            } else if (cur.contains(range.mHi)) {
                u16 oldHi = cur.getHi();
                cur.mHi = lo - 1;
                mRanges.insertSorted(CharRange(range.mHi + 1, oldHi));
                if (gAllocFailed) {
                    return *this;
                }
                i++;
            } else {
                cur.mHi = lo - 1;
            }
        } else {
            if (cur.contains(range.mHi)) {
                cur.mLo = range.mHi + 1;
            }
        }
    }
    return *this;
}

// 801E4934
CharSet &CharSet::subtract(const CharSet &other) {
    for (u32 i = 0; i < other.mRanges.size(); i++) {
        remove(other.mRanges[i]);
        if (gAllocFailed) {
            return *this;
        }
    }
    return *this;
}

