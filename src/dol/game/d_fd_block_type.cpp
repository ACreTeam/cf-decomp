// 800812C8
int getKind(int type) {
    if (type < BLOCK_TYPE_NUM) {
        return l_typeKind[type];
    }
    return 0;
}

// 800812E8
int findKind(int flags) {
    const int *kindFlags = l_kindFlags;
    for (int i = 0; i < BLOCK_KIND_NUM; i++) {
        if (flags == *kindFlags++) {
            return i;
        }
    }
    return BLOCK_KIND_NONE;
}

// 80081324
int getTypeFlags(int type) {
    return getKindFlags(getKind(type));
}

// 80081348
u32 getKindFlags(int kind) {
    if (kind < BLOCK_KIND_NUM) {
        return l_kindFlags[kind];
    }
    return 0;
}

// 8008136C
u8 getRiverNum(int kind) {
    u32 flags = getKindFlags(kind);
    if (flags & BLOCK_KIND_FLAG_RIVER) {
        u8 num = 0;
        if (flags & BLOCK_KIND_FLAG_RIVER_S0) {
            num = 1;
        }
        if (flags & BLOCK_KIND_FLAG_RIVER_E0) {
            num++;
        }
        if (flags & BLOCK_KIND_FLAG_RIVER_W0) {
            num++;
        }
        if (flags & BLOCK_KIND_FLAG_RIVER_E1) {
            num++;
        }
        if (flags & BLOCK_KIND_FLAG_RIVER_S1) {
            num++;
        }
        if (flags & BLOCK_KIND_FLAG_RIVER_W1) {
            num++;
        }
        if (flags & BLOCK_KIND_FLAG_RIVER_S2) {
            num++;
        }
        return num;
    }
    return 0;
}

// 80081410
int getTypeIndex(int type) {
    int index = 0;
    int flags = getTypeFlags(type);
    for (u32 i = 0; i < BLOCK_TYPE_NUM; i++) {
        if (flags == getTypeFlags(i)) {
            if (type == (int)i) {
                return index;
            }
            index++;
        }
    }
    return -1;
}

// 80081494
int getNthType(int flags, u32 index) {
    u32 n = 0;
    for (u32 i = 0; i < BLOCK_TYPE_NUM; i++) {
        if (flags == getTypeFlags(i)) {
            if (n == index) {
                return i;
            }
            n++;
        }
    }
    return -1;
}

// 80081514
int getBridgeType(int type) {
    int flags = getTypeFlags(type);
    int index = getTypeIndex(type);
    if (index != -1) {
        int bridge = getNthType(flags | BLOCK_KIND_FLAG_BRIDGE, index);
        if (bridge != -1) {
            return bridge;
        }
    }
    return type;
}

