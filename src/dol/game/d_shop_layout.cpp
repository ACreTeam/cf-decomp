// 8015FD20
void dShopLayout_applySale(dShopSale_c sale) {
    int scene = sale.mScene;
    switch (scene) {
    case SCENE_RM_SHOP0:
    case SCENE_RM_SHOP1:
    case SCENE_RM_SHOP2:
    case SCENE_RM_SHOP3_F1:
    case SCENE_RM_SHOP3_F2:
        if (sale.mSlot != 0xFF) {
            dSaveTown_c *town = dSaveData_c::getTown();
            town->mShops.mShop.sell(scene, sale.mSlot, sale.mUnitX, sale.mUnitZ);
        }
        dSaveData_c::getTown()->mShops.mShop.addSales(sale.mPrice, sale.mFlag);
        break;
    case SCENE_RM_TAILOR:
        {
            dSaveTown_c *town = dSaveData_c::getTown();
            town->mShops.mShopTailor.sell(scene, sale.mSlot, sale.mUnitX, sale.mUnitZ);
        }
        break;
    }
}
