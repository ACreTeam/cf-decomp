// 8015F748
const dShopLayout_t *dShopLayout_get(u8 scene) {
    switch (scene) {
    case SCENE_RM_SHOP0:
        return &sShopLayouts[0];
    case SCENE_RM_SHOP1:
        return &sShopLayouts[1];
    case SCENE_RM_SHOP2:
        return &sShopLayouts[2];
    case SCENE_RM_SHOP3_F1:
        return &sShopLayouts[3];
    case SCENE_RM_SHOP3_F2:
        return &sShopLayouts[4];
    case SCENE_RM_BROKER:
        return &sBrokerLayout;
    case SCENE_RM_TAILOR:
        return &sTailorLayout;
    case SCENE_RM_GRACE: {
        dTimeStamp_c today(dTime_c::getCurrent());
        today.toDayStart();
        dSaveTown_c *town = dSaveData_c::getTown();
        switch (town->mShops.mShopGrace.getLayoutType(today.get().month)) {
        case 0:
            return &sGraceLayout0;
        case 1:
            return &sGraceLayout1;
        case 2:
            return &sGraceLayout2;
        case 3:
            return &sGraceLayout3;
        }
        break;
    }
    }
    return &sShopLayouts[0];
}

// 8015F870: the first unit of the current shop showing `kind` that has no item on it.
BOOL dShopLayout_findFreeUnit(int kind, int *unitX, int *unitZ) {
    const dShopLayout_t *layout = dShopLayout_get(getCurrentScene());
    for (int z = 0; z < UT_Z_NUM; z++) {
        for (int x = 0; x < UT_X_NUM; x++) {
            dItem::Item *item = fn_80190C44(0)->getItem(x, z, 0);
            if (kind == (*layout)[z][x] && item != NULL && item->mId == dItem::ITEM_ID_NONE) {
                *unitX = x;
                *unitZ = z;
                return TRUE;
            }
        }
    }
    return FALSE;
}

// 8015F930: the stock slot of the item on a unit of the current shop. Nook's saplings are slots
// 14.., in layout order of the KIND_SEEDLING units; everything else is looked up by item id.
int dShopLayout_getSlot(int unitX, int unitZ) {
    u16 id;

    dItem::Item item = fn_80190C44(0)->getUnitItem(unitX, unitZ);
    if (!dItem::isRealItemId(item.mId)) {
        return -1;
    }

    switch (getCurrentScene()) {
    case SCENE_RM_SHOP0:
    case SCENE_RM_SHOP1:
    case SCENE_RM_SHOP2:
    case SCENE_RM_SHOP3_F1:
    case SCENE_RM_SHOP3_F2:
        switch (item.getKind()) {
        case dItem::KIND_SEEDLING: {
            int n = 0;
            const dShopLayout_t *layout = dShopLayout_get(getCurrentScene());
            for (int z = 0; z < UT_Z_NUM; z++) {
                for (int x = 0; x < UT_X_NUM; x++) {
                    if ((*layout)[z][x] == dItem::KIND_SEEDLING) {
                        if (unitX == x && unitZ == z) {
                            return n + 14;
                        }
                        n++;
                    }
                }
            }
            break;
        }
        default:
            for (int i = 0; i < 36; i++) {
                dSaveTown_c *town = dSaveData_c::getTown();
                id = item.mId;
                if (id == town->mShops.mShop.getItem(i)) {
                    return i;
                }
            }
            break;
        }
        break;
    case SCENE_RM_BROKER:
        for (int i = 0; i < 3; i++) {
            dSaveTown_c *town = dSaveData_c::getTown();
            id = item.mId;
            if (id == town->mShops.mShopGallery.getItem(i)) {
                return i;
            }
        }
        break;
    case SCENE_RM_TAILOR:
        for (int i = 0; i < 14; i++) {
            dSaveTown_c *town = dSaveData_c::getTown();
            id = item.mId;
            if (id == town->mShops.mShopTailor.getItem(i)) {
                return i;
            }
        }
        break;
    case SCENE_RM_GRACE:
        for (int i = 0; i < 23; i++) {
            dSaveTown_c *town = dSaveData_c::getTown();
            id = item.mId;
            if (id == town->mShops.mShopGrace.getItem(i, 1)) {
                return i;
            }
        }
        break;
    }
    return -1;
}

// 8015FBF8: whether the item on a unit of the current shop is sold; TRUE outside the shops.
BOOL dShopLayout_isSlotSold(int unitX, int unitZ) {
    dSaveTown_c *town;
    switch (getCurrentScene()) {
    case SCENE_RM_SHOP0:
    case SCENE_RM_SHOP1:
    case SCENE_RM_SHOP2:
    case SCENE_RM_SHOP3_F1:
    case SCENE_RM_SHOP3_F2:
        town = dSaveData_c::getTown();
        return town->mShops.mShop.isSold(dShopLayout_getSlot(unitX, unitZ));
    case SCENE_RM_BROKER:
        town = dSaveData_c::getTown();
        return town->mShops.mShopGallery.isSold(dShopLayout_getSlot(unitX, unitZ));
    case SCENE_RM_TAILOR:
        town = dSaveData_c::getTown();
        return town->mShops.mShopTailor.isSold(dShopLayout_getSlot(unitX, unitZ));
    case SCENE_RM_GRACE:
        town = dSaveData_c::getTown();
        return town->mShops.mShopGrace.isSold(dShopLayout_getSlot(unitX, unitZ));
    }
    return TRUE;
}

