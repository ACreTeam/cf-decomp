// 800B6580
void dHmnAnm_c::curveMtx(mMtx_c *out, const mMtx_c *in, f32 baseY) {
    if (!isOutdoorScene(getCurrentScene())) {
        *out = *in;
        return;
    }
    mVec3_c pos(in->m[0][3], in->m[1][3] + baseY, in->m[2][3]);
    mVec3_c curved;
    s16 angle = dWorld::curvePositionSimple(&curved, &pos);
    out->m[2][3] = curved.z;
    out->m[1][3] = curved.y - dWorld::getRadius() - baseY;
    if (angle != 0) {
        out->XrotM(mAng(angle));
    }
}

