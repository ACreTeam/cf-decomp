// 800A6E00
int Item::getFruitTreeType() {
    u16 id = mId;
    int type = 7;
    if (inRange(id, 0x19, 0x20)) {
        return 0;
    }
    if (inRange(id, 0x21, 0x28)) {
        return 1;
    }
    if (inRange(id, 0x29, 0x30)) {
        return 2;
    }
    if (inRange(id, 0x31, 0x38)) {
        return 3;
    }
    if (inRange(id, 0x39, 0x40)) {
        return 4;
    }
    if (inRange(id, 0x41, 0x48)) {
        return 5;
    }
    if (inRange(id, 0x49, 0x4D)) {
        type = 6;
    }
    return type;
}

// 800A6F20
Item Item::getPickItem() const {
    Item result = *this;
    if (isFlower()) {
        result = Item(0x59F, mId - 0x9E, FALSE);
    } else if (mId == 0xDE) {
        result = Item(ITEM_IDX_DANDELIONS);
    } else if (mId == 0xDF) {
        result = Item(ITEM_IDX_DANDELION_PUFFS);
    } else if (inRange(mId, 0x95, 0x9D)) {
        result = Item(0x18A, mId - 0x95, FALSE);
    } else if (getKind() == KIND_MUSH_FTR) {
        int n = seeker_c::get()->findLike(*this);
        if (n >= 0 && n < 12) {
            result.setFromIndex(sMushFtrItems[n]);
        } else {
            result.setFromIndex(ITEM_IDX_FOREST_WALL_WALL);
        }
    }
    return result;
}

