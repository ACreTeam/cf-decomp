// 800A622C
u16 Item::getMoneyItem(int amount, BOOL roundUp, int *remainder) {
    Item item;
    if (remainder != NULL) {
        *remainder = 0;
    }
    if (roundUp) {
        item.setFromIndex(ITEM_IDX_99000_BELLS);
        if (item.getPrice() < amount) {
            return ITEM_ID_NONE;
        }
        for (int i = 0x53; i <= 0xBE; i++) {
            item.setFromIndex(i);
            int price = item.getPrice();
            if (price >= amount) {
                if (remainder != NULL) {
                    *remainder = price - amount;
                }
                return item.mId;
            }
        }
    } else {
        item.setFromIndex(ITEM_IDX_100_BELLS);
        if (item.getPrice() > amount) {
            return ITEM_ID_NONE;
        }
        for (int i = 0xBE; i >= 0x53; i--) {
            item.setFromIndex(i);
            int price = item.getPrice();
            if (price <= amount) {
                if (remainder != NULL) {
                    *remainder = amount - price;
                }
                return item.mId;
            }
        }
    }
    return ITEM_ID_NONE;
}

